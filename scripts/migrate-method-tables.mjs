// Idempotently create the learning-method tables (B1/B3/B4) on Supabase Postgres.
// Mirrors the word_details + user_word_examples blocks in supabase/schema.sql, but
// safe to run on a populated DB (the full schema.sql has non-idempotent triggers).
// Env (.env.local): SUPABASE_DB_HOST, SUPABASE_DB_PASSWORD.
import pg from "pg";
import { loadEnv } from "./_supabase.mjs";

loadEnv();
const host = process.env.SUPABASE_DB_HOST;
const password = process.env.SUPABASE_DB_PASSWORD;
if (!host || !password) {
  console.error("Missing SUPABASE_DB_HOST / SUPABASE_DB_PASSWORD in .env.local");
  process.exit(1);
}

const SQL = `
create table if not exists public.word_details (
  word_id         integer primary key references public.words(id) on delete cascade,
  definition_en   text,
  nuance_vi       text,
  usage_contexts  jsonb   not null default '[]'::jsonb,
  collocations    jsonb   not null default '[]'::jsonb,
  model           text,
  generated_at    timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
alter table public.word_details add column if not exists collocations jsonb not null default '[]'::jsonb;
drop trigger if exists word_details_updated_at on public.word_details;
create trigger word_details_updated_at before update on public.word_details
  for each row execute function public.set_updated_at();

create table if not exists public.user_word_examples (
  id          bigint generated by default as identity primary key,
  user_id     text    not null,
  word_id     integer not null references public.words(id) on delete cascade,
  text        text    not null,
  feedback    text,
  created_at  timestamptz not null default now()
);
create index if not exists idx_uwe_user_word on public.user_word_examples(user_id, word_id);
`;

const client = new pg.Client({
  host,
  port: 5432,
  user: "postgres",
  password,
  database: "postgres",
  ssl: { rejectUnauthorized: false },
  connectionTimeoutMillis: 15000,
});

try {
  await client.connect();
  console.error("Connected:", host);
  await client.query(SQL);
  await client.query("notify pgrst, 'reload schema';");
  const { rows } = await client.query(
    "select table_name from information_schema.tables where table_schema='public' and table_name in ('word_details','user_word_examples') order by table_name",
  );
  console.error("method tables present:", rows.map((r) => r.table_name).join(", ") || "(none)");
  await client.end();
  process.exit(0);
} catch (e) {
  console.error("MIGRATE ERROR:", e.message);
  await client.end().catch(() => {});
  process.exit(2);
}
